// Prisma allows exactly one datasource provider per schema and the provider
// cannot come from an environment variable. The canonical schema targets
// PostgreSQL (Render/Neon, VPS docker stack); this script materializes the same
// models as SQLite so local development stays zero-config.
//
//   npm run db:sqlite
//
// The output is generated, git-ignored, and never edited by hand.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const prismaDir = path.resolve(here, '..', 'prisma');
const source = path.join(prismaDir, 'schema.prisma');
const target = path.join(prismaDir, 'schema.sqlite.prisma');

const POSTGRES = 'provider = "postgresql"';
const canonical = fs.readFileSync(source, 'utf8');

if (!canonical.includes(POSTGRES)) {
  console.error(`[schema-sqlite] "${POSTGRES}" not found in prisma/schema.prisma — refusing to guess.`);
  process.exit(1);
}

const body = canonical.replace(POSTGRES, 'provider = "sqlite"');
fs.writeFileSync(
  target,
  '// GENERATED by scripts/schema-sqlite.mjs — do not edit, do not commit.\n' + body,
);

console.log('[schema-sqlite] wrote prisma/schema.sqlite.prisma');
